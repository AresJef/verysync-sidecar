//! Explicit bounded payload transfers. Local output names are caller selected.
use crate::{Error, OperationCompletion, OperationOptions, Result};
use std::{
    fmt,
    path::{Path, PathBuf},
    time::Duration,
};

/// An inclusive, finite HTTP byte range. Suffix/open-ended ranges are not guessed.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ResourceByteRange {
    pub(crate) first: u64,
    pub(crate) last: u64,
}
impl ResourceByteRange {
    /// Select a nonempty inclusive interval whose length fits in u64.
    pub fn new(first: u64, last: u64) -> Result<Self> {
        if first > last || last == u64::MAX {
            return Err(Error::InvalidConfiguration {
                reason: "invalid finite byte range",
            });
        }
        Ok(Self { first, last })
    }
    /// First included byte offset.
    pub fn first(self) -> u64 {
        self.first
    }
    /// Last included byte offset.
    pub fn last(self) -> u64 {
        self.last
    }
}

/// Total payload bound and complete-operation deadline, independent of the
/// small buffered management-response limit. Defaults: 1 GiB and five minutes.
#[derive(Clone, Debug)]
pub struct ResourceTransferOptions {
    /// Maximum bytes streamed into the local file or supplied upload body.
    pub max_bytes: u64,
    /// Deadline including identity, local I/O, transfer and verification.
    pub deadline: Duration,
}
impl Default for ResourceTransferOptions {
    fn default() -> Self {
        Self {
            max_bytes: 1024 * 1024 * 1024,
            deadline: Duration::from_secs(300),
        }
    }
}
impl ResourceTransferOptions {
    pub(crate) fn validate(&self) -> Result<()> {
        if self.max_bytes == 0
            || self.deadline.is_zero()
            || self.deadline > Duration::from_secs(86400)
        {
            return Err(Error::InvalidConfiguration {
                reason: "transfer needs a positive byte bound and a deadline of at most one day",
            });
        }
        Ok(())
    }
}

/// The target's explicitly selected native archive format.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ResourceArchiveFormat {
    /// ZIP archive generated by the engine, without SDK extraction.
    Zip,
    /// Uncompressed native TAR archive.
    Tar,
    /// Native gzip-compressed TAR archive.
    TarGzip,
    /// Native bzip2-compressed TAR archive.
    TarBzip2,
    /// Native XZ-compressed TAR archive.
    TarXz,
    /// Native LZ4-frame-compressed TAR archive.
    TarLz4,
    /// Native Snappy-frame-compressed TAR archive.
    TarSnappy,
}
impl ResourceArchiveFormat {
    pub(crate) fn name(self) -> &'static str {
        match self {
            Self::Zip => "zip",
            Self::Tar => "tar",
            Self::TarGzip => "targz",
            Self::TarBzip2 => "tarbz2",
            Self::TarXz => "tarxz",
            Self::TarLz4 => "tarlz4",
            Self::TarSnappy => "tarsz",
        }
    }
}

impl ResourceArchiveFormat {
    pub(crate) fn media_type(self) -> &'static str {
        match self {
            Self::Zip => "application/zip",
            Self::TarGzip => "application/x-gzip",
            _ => "application/octet-stream",
        }
    }
}

/// Actual streamed local bytes and their SHA-256. A completed download does not
/// claim that the remote resource stayed unchanged during the request.
pub struct ResourceDownload {
    /// Bytes actually written and flushed to the new local file.
    pub bytes: u64,
    /// SHA-256 of exactly those bytes, including a selected range/archive.
    pub sha256: [u8; 32],
    pub(crate) media_type: Option<String>,
    pub(crate) content_range: Option<String>,
}
impl ResourceDownload {
    /// Advertised media type, untrusted remote data; not used as a local name.
    pub fn media_type(&self) -> Option<&str> {
        self.media_type.as_deref()
    }
    /// Actual Content-Range, required and checked for explicit range downloads.
    pub fn content_range(&self) -> Option<&str> {
        self.content_range.as_deref()
    }
}
impl fmt::Debug for ResourceDownload {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ResourceDownload")
            .field("bytes", &self.bytes)
            .finish_non_exhaustive()
    }
}

/// Limits and opt-in behavior for a verified single-file download.
#[derive(Clone, Debug)]
pub struct VerifiedDownloadOptions {
    pub(crate) max_bytes: u64,
    pub(crate) operation: OperationOptions,
    pub(crate) resume: bool,
    pub(crate) expected_sha256: Option<[u8; 32]>,
}

impl VerifiedDownloadOptions {
    /// Set the maximum output length and a single deadline for the operation.
    pub fn new(max_bytes: u64, operation: OperationOptions) -> Self {
        Self {
            max_bytes,
            operation,
            resume: false,
            expected_sha256: None,
        }
    }

    /// Permit one suffix request after an interrupted response, provided the
    /// authenticated source digest and the staged prefix are still verified.
    pub fn resume_once(mut self) -> Self {
        self.resume = true;
        self
    }

    /// Also require an independently known SHA-256 before opening a data stream.
    pub fn expected_sha256(mut self, sha256: [u8; 32]) -> Self {
        self.expected_sha256 = Some(sha256);
        self
    }
}

/// Evidence from downloading one specific remote version into a new file.
#[non_exhaustive]
pub struct VerifiedDownloadReport {
    /// The verified write received by the caller's local destination.
    pub completed: Option<ResourceDownload>,
    /// Bytes accepted for the SDK's private staging file.
    pub staged_bytes: u64,
    /// How many data requests entered the HTTP transport.
    pub data_requests: u8,
    /// The original trusted source SHA-256, if available.
    pub source_sha256: Option<[u8; 32]>,
    /// The requested suffix, if the SDK tried one.
    pub resumed_range: Option<ResourceByteRange>,
    /// The interruption that led to checking if a suffix request was safe.
    pub initial_error: Option<Error>,
    /// The reason the selected download or local publication remained incomplete.
    pub error: Option<Error>,
    /// An error removing private staging after the output was already complete.
    pub cleanup_error: Option<Error>,
    pub(crate) partial: Option<PathBuf>,
    pub(crate) publication_entered: bool,
}

impl VerifiedDownloadReport {
    /// See the private path of retained data. Inspect it explicitly before use.
    /// The SDK cannot confirm it as a complete download.
    pub fn retained_staging_path(&self) -> Option<&Path> {
        self.partial.as_deref()
    }

    /// Summarize whether the verified file was published at the destination.
    pub fn completion(&self) -> OperationCompletion {
        if self.completed.is_some() {
            OperationCompletion::Completed
        } else if self.publication_entered {
            OperationCompletion::Unconfirmed
        } else if self.staged_bytes > 0 {
            OperationCompletion::PartiallyCompleted
        } else {
            OperationCompletion::GoalNotMet
        }
    }
}

impl fmt::Debug for VerifiedDownloadReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("VerifiedDownloadReport")
            .field("completion", &self.completion())
            .field("staged_bytes", &self.staged_bytes)
            .field("data_requests", &self.data_requests)
            .field("resumed_range", &self.resumed_range)
            .field("initial_error", &self.initial_error)
            .field("error", &self.error)
            .field("cleanup_error", &self.cleanup_error)
            .finish_non_exhaustive()
    }
}

impl fmt::Display for VerifiedDownloadReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if let Some(download) = &self.completed {
            return write!(
                f,
                "The verified file was saved with {} bytes.",
                download.bytes
            );
        }
        if self.publication_entered {
            f.write_str("The local file could not be confirmed at the chosen destination. Check that destination before trying again.")?;
        } else {
            f.write_str("The download did not finish.")?;
        }
        if let Some(source) = &self.error {
            write!(f, " {source}")?;
        }
        if self.partial.is_some() {
            f.write_str(" The SDK retained a private staging file for inspection.")?;
        }
        Ok(())
    }
}

/// Whether the engine may replace an existing upload target. This does not
/// provide a transaction against other management/filesystem writers.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ResourceUploadConflict {
    /// Ask the engine to refuse an existing target.
    RejectExisting,
    /// Explicitly permit replacing the target's contents.
    Replace,
}

/// A complete local input streamed once and a subsequent matching remote digest.
/// Keep the input immutable until completion. A checksum is an observation, not
/// a lock against later writers or proof that peers received the file.
#[derive(Clone, Debug)]
pub struct ResourceUpload {
    /// Complete local input length.
    pub bytes: u64,
    /// Local input digest also observed at the remote target after upload.
    pub sha256: [u8; 32],
}
