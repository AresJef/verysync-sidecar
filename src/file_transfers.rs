//! Explicit bounded payload transfers. Local output names are caller selected.
use crate::{Error, Result};
use std::{fmt, time::Duration};

/// An inclusive, finite HTTP byte range. Suffix/open-ended ranges are not guessed.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ResourceByteRange {
    pub(crate) first: u64,
    pub(crate) last: u64,
}
impl ResourceByteRange {
    /// Select a nonempty inclusive interval whose length fits in u64.
    pub fn new(first: u64, last: u64) -> Result<Self> {
        if first > last || last == u64::MAX {
            return Err(Error::InvalidConfiguration {
                reason: "invalid finite byte range",
            });
        }
        Ok(Self { first, last })
    }
    /// First included byte offset.
    pub fn first(self) -> u64 {
        self.first
    }
    /// Last included byte offset.
    pub fn last(self) -> u64 {
        self.last
    }
}

/// Total payload bound and complete-operation deadline, independent of the
/// small buffered management-response limit. Defaults: 1 GiB and five minutes.
#[derive(Clone, Debug)]
pub struct ResourceTransferOptions {
    /// Maximum bytes streamed into the local file or supplied upload body.
    pub max_bytes: u64,
    /// Deadline including identity, local I/O, transfer and verification.
    pub deadline: Duration,
}
impl Default for ResourceTransferOptions {
    fn default() -> Self {
        Self {
            max_bytes: 1024 * 1024 * 1024,
            deadline: Duration::from_secs(300),
        }
    }
}
impl ResourceTransferOptions {
    pub(crate) fn validate(&self) -> Result<()> {
        if self.max_bytes == 0
            || self.deadline.is_zero()
            || self.deadline > Duration::from_secs(86400)
        {
            return Err(Error::InvalidConfiguration {
                reason: "transfer needs a positive byte bound and a deadline of at most one day",
            });
        }
        Ok(())
    }
}

/// The target's explicitly selected native archive format.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ResourceArchiveFormat {
    /// ZIP archive generated by the engine, without SDK extraction.
    Zip,
    /// Uncompressed native TAR archive.
    Tar,
    /// Native gzip-compressed TAR archive.
    TarGzip,
    /// Native bzip2-compressed TAR archive.
    TarBzip2,
    /// Native XZ-compressed TAR archive.
    TarXz,
    /// Native LZ4-frame-compressed TAR archive.
    TarLz4,
    /// Native Snappy-frame-compressed TAR archive.
    TarSnappy,
}
impl ResourceArchiveFormat {
    pub(crate) fn name(self) -> &'static str {
        match self {
            Self::Zip => "zip",
            Self::Tar => "tar",
            Self::TarGzip => "targz",
            Self::TarBzip2 => "tarbz2",
            Self::TarXz => "tarxz",
            Self::TarLz4 => "tarlz4",
            Self::TarSnappy => "tarsz",
        }
    }
}

impl ResourceArchiveFormat {
    pub(crate) fn media_type(self) -> &'static str {
        match self {
            Self::Zip => "application/zip",
            Self::TarGzip => "application/x-gzip",
            _ => "application/octet-stream",
        }
    }
}

/// Actual streamed local bytes and their SHA-256. A completed download does not
/// claim that the remote resource stayed unchanged during the request.
pub struct ResourceDownload {
    /// Bytes actually written and flushed to the new local file.
    pub bytes: u64,
    /// SHA-256 of exactly those bytes, including a selected range/archive.
    pub sha256: [u8; 32],
    pub(crate) media_type: Option<String>,
    pub(crate) content_range: Option<String>,
}
impl ResourceDownload {
    /// Advertised media type, untrusted remote data; not used as a local name.
    pub fn media_type(&self) -> Option<&str> {
        self.media_type.as_deref()
    }
    /// Actual Content-Range, required and checked for explicit range downloads.
    pub fn content_range(&self) -> Option<&str> {
        self.content_range.as_deref()
    }
}
impl fmt::Debug for ResourceDownload {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ResourceDownload")
            .field("bytes", &self.bytes)
            .finish_non_exhaustive()
    }
}

/// Whether the engine may replace an existing upload target. This does not
/// provide a transaction against other management/filesystem writers.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ResourceUploadConflict {
    /// Ask the engine to refuse an existing target.
    RejectExisting,
    /// Explicitly permit replacing the target's contents.
    Replace,
}

/// A complete local input streamed once and a subsequent matching remote digest.
/// Keep the input immutable until completion. A checksum is an observation, not
/// a lock against later writers or proof that peers received the file.
#[derive(Clone, Debug)]
pub struct ResourceUpload {
    /// Complete local input length.
    pub bytes: u64,
    /// Local input digest also observed at the remote target after upload.
    pub sha256: [u8; 32],
}
